    @staticmethod
    def build_vhr_program(model: VHRModel) -> str:
        """The model as an *equation program* that the Studio's live Equation tab (expression_engine) can
        load, edit and render - closing the image -> equation -> image loop with one text file."""
        VHRExporterSuite._require_fitted(model, "equation program")
        g = model.grid
        lines: List[str] = [
            f"#! grid {g.width} {g.height} {int(round(g.m0))} {int(round(g.n0))} {_fmt(g.scale)}",
            f"# {model.title}",
            f"# {len(model.trig_terms)} cosine terms, {len(model.primitives)} primitives.  Pixel (m, n) = (1..{g.width}, 1..{g.height}).",
            "# Rendered with the VHR branchless quantiser F(x) = floor(255 e^{-e^{-1000x}} |x|^{e^{-e^{1000(x-1)}}}).",
        ]

        def vec(name: str, values) -> None:
            lines.append(f"{name} = [" + ", ".join(_fmt(v) for v in values) + "]")

        if model.trig_terms:
            vec("U", [t.u for t in model.trig_terms])
            vec("V", [t.v for t in model.trig_terms])
            vec("A0", [t.c0 for t in model.trig_terms])
            vec("A1", [t.c1 for t in model.trig_terms])
            vec("A2", [t.c2 for t in model.trig_terms])
