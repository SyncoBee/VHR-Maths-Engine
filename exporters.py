    @staticmethod
    def export_vhr_program(model: VHRModel, filepath: str) -> None:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(VHRExporterSuite.build_vhr_program(model))

    @staticmethod
    def export_json(model: VHRModel, filepath: str) -> None:
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(model.to_dict(), f, indent=2)

    @staticmethod
    def load_json(filepath: str) -> VHRModel:
        with open(filepath, "r", encoding="utf-8") as f:
            return VHRModel.from_dict(json.load(f))
