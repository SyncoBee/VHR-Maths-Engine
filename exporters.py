_TEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


class ExportError(RuntimeError):
    """Raised when a model cannot be exported in the requested format (shown to the user as a message)."""


def _tex_escape(text: str) -> str:
    return "".join(_TEX_SPECIAL.get(ch, ch) for ch in text)


def _fmt(value: float) -> str:
    """Shortest repr that round-trips a float64 (keeps exports bit-identical to the app)."""
    return repr(float(value))


class VHRExporterSuite:
    """Exports VHR models to Compilable LaTeX, Standalone Python Scripts, GLSL Shaders, and JSON."""

    @staticmethod
    def _require_fitted(model: VHRModel, what: str) -> None:
        if not model.trig_terms and not model.primitives:
            raise ExportError(
                f"'{model.title}' is a procedural catalog formula (not a fitted image), so a standalone {what} "
                f"cannot be generated from stored constants. Use the LaTeX or JSON export instead."
            )

    @staticmethod
    def export_compilable_latex(model: VHRModel, filepath: str, max_den: int = 1000, max_table_terms: int = 2000) -> None:
        """Exports a complete compilable LaTeX document including explicit rationalized tables."""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write("\\documentclass[10pt]{article}\n")
            f.write("\\usepackage[margin=0.4in,landscape]{geometry}\n")
            f.write("\\usepackage{amsmath,amssymb,graphicx,longtable}\n\\begin{document}\n\\begin{center}\n")
            f.write(f"\\textbf{{{_tex_escape(model.title)}}}\\\\[0.8em]\n")
            for line in model.latex_lines:
                f.write("\\resizebox{\\linewidth}{!}{$\\displaystyle " + line + "$}\\\\[0.6em]\n")

            if model.primitives:
                f.write("\\vspace{0.5em}\\textbf{Exact Rationalized Primitive Parameters $(p=1,\\dots," + str(len(model.primitives)) + ")$:}\\\\[0.4em]\n")
                for idx, p in enumerate(model.primitives, start=1):
                    x0_f = AlgebraicCore.to_latex_rational(p.x0, max_den)
                    y0_f = AlgebraicCore.to_latex_rational(p.y0, max_den)
                    a_f = AlgebraicCore.to_latex_rational(p.a, max_den)
                    b_f = AlgebraicCore.to_latex_rational(p.b, max_den)
                    c0_f = AlgebraicCore.to_latex_rational(p.c0, max_den)
                    c1_f = AlgebraicCore.to_latex_rational(p.c1, max_den, signed=True)
                    c2_f = AlgebraicCore.to_latex_rational(p.c2, max_den, signed=True)
                    th_f = AlgebraicCore.to_latex_rational(p.theta, max_den)
                    k_f = AlgebraicCore.to_latex_rational(p.k, max_den)
                    f.write(f"$p={idx}: (x_p, y_p)=\\left({x0_f}, {y0_f}\\right),\\ (a_p, b_p)=\\left({a_f}, {b_f}\\right),\\ "
                            f"\\theta_p={th_f},\\ k_p={k_f},\\ W_{{p,s}}={c0_f}{c1_f}s{c2_f}s^2$\\\\[0.2em]\n")

            if model.trig_terms:
                shown = model.trig_terms[:max_table_terms]
                f.write("\\end{center}\n\\vspace{0.5em}\\noindent\\textbf{Cosine coefficients ")
                f.write(f"(strongest {len(shown)} of {len(model.trig_terms)}; "
                        f"$\\alpha_{{j,k}}$ are the polynomial coefficients in $s$):}}\n")
                f.write("{\\small\\begin{longtable}{rrrrrr}\n$k$ & $u_k$ & $v_k$ & $\\alpha_{0,k}$ & $\\alpha_{1,k}$ & $\\alpha_{2,k}$\\\\\\hline\\endhead\n")
                for k, t in enumerate(shown, start=1):
                    f.write(f"{k} & {t.u} & {t.v} & {t.c0:.7f} & {t.c1:.7f} & {t.c2:.7f}\\\\\n")
                f.write("\\end{longtable}}\n")
                f.write("\\begin{center}\n")

            f.write("\\end{center}\n\\end{document}\n")

