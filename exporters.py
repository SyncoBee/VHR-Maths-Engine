    t0 = np.clip(-1000.0 * x, -500.0, 500.0)
    t1 = np.clip(1000.0 * (x - 1.0), -500.0, 500.0)
    val = 255.0 * np.exp(-np.exp(t0)) * (np.maximum(np.abs(x), 1e-15) ** np.exp(-np.exp(t1)))
    return np.floor(np.clip(val + 1e-9, 0.0, 255.0)).astype(np.uint8)


